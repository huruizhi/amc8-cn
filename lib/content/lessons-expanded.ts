import type { Lesson, LessonExercise, LessonOption } from "./lessons";

const labels: LessonOption["label"][] = ["A", "B", "C", "D"];

function options(values: string[]): LessonOption[] {
  return values.map((value, index) => ({ label: labels[index], value }));
}

function exercise(
  id: string,
  prompt: string,
  values: string[],
  answer: LessonOption["label"],
  explanation: string,
  level?: LessonExercise["level"],
): LessonExercise {
  return { id, prompt, options: options(values), answer, explanation, level };
}

function example(title: string, prompt: string, steps: string[], answer: string) {
  return { title, prompt, steps, answer };
}

